"""Pure absolute-position descriptors for already normalized text tokens.

This module deliberately accepts only a token sequence and a seed. It has no
record-ID, target, model, vectorizer, filesystem, or dataset dependency.
"""
from __future__ import annotations

from collections import Counter
import hashlib
import json
from typing import Any, Sequence


def _tokens(values: Sequence[str]) -> tuple[str, ...]:
    if isinstance(values, (str, bytes)):
        raise TypeError("tokens must be a sequence of normalized token strings")
    result = tuple(values)
    if any(not isinstance(value, str) for value in result):
        raise TypeError("every token must be a string")
    return result


def token_thirds(token_count: int) -> tuple[int, ...]:
    """Assign each zero-based token index to floor(3*i/n), with empty -> ()."""
    n = int(token_count)
    if n < 0 or n != token_count:
        raise ValueError("token_count must be a nonnegative integer")
    if n == 0:
        return ()
    return tuple((3 * index) // n for index in range(n))


def _counts(tokens: tuple[str, ...], segments: tuple[int, ...]) -> tuple[dict[str, int], ...]:
    result = [Counter(), Counter(), Counter()]
    for token, segment in zip(tokens, segments):
        result[segment][token] += 1
    return tuple(dict(sorted(counter.items())) for counter in result)


def absolute_position_features(tokens: Sequence[str]) -> dict[str, Any]:
    """Return normalized-token counts in first, middle, and final thirds.

    The feature is a coarse positional distribution; it does not preserve
    within-third order and is not a semantic or quality measure.
    """
    values = _tokens(tokens)
    segment_ids = token_thirds(len(values))
    sizes = tuple(segment_ids.count(segment) for segment in range(3))
    return {
        "token_count": len(values),
        "segment_sizes": sizes,
        "segment_counts": _counts(values, segment_ids),
        "empty": len(values) == 0,
    }


def deterministic_order_shuffle(tokens: Sequence[str], *, seed: int = 42) -> dict[str, Any]:
    """Shuffle order using seed plus a stable digest of normalized text.

    The permutation is generated by sorting per-occurrence SHA-256 keys, so
    it does not depend on a row ID, target, global RNG state, or NumPy RNG
    implementation. It preserves the exact bag and all three segment sizes.
    """
    values = _tokens(tokens)
    if not isinstance(seed, int) or isinstance(seed, bool):
        raise TypeError("seed must be an integer")
    canonical = json.dumps(values, ensure_ascii=False, separators=(",", ":"),
                           allow_nan=False).encode("utf-8", errors="surrogatepass")
    text_digest = hashlib.sha256(canonical).digest()
    seed_bytes = int(seed).to_bytes(16, "big", signed=True)
    order = sorted(
        range(len(values)),
        key=lambda index: (hashlib.sha256(b"positional-text-v1" + seed_bytes + text_digest
                                         + int(index).to_bytes(8, "big", signed=False)).digest(), index),
    )
    source_positions = tuple(order)
    shuffled = tuple(values[index] for index in source_positions)
    shuffled_features = absolute_position_features(shuffled)
    original_features = absolute_position_features(values)
    original_segments = token_thirds(len(values))
    moved = sum(original_segments[source] != token_thirds(len(values))[new]
                for new, source in enumerate(source_positions))
    if (Counter(shuffled) != Counter(values)
            or shuffled_features["token_count"] != original_features["token_count"]
            or shuffled_features["segment_sizes"] != original_features["segment_sizes"]):
        raise RuntimeError("order shuffle did not preserve bag, length, and segment sizes")
    return {
        "tokens": shuffled,
        "source_positions": source_positions,
        "token_count": len(values),
        "segment_sizes": shuffled_features["segment_sizes"],
        "segment_counts": shuffled_features["segment_counts"],
        "stable_normalized_text_digest_sha256": text_digest.hex(),
        "fraction_of_occurrences_moved_between_thirds": moved / len(values) if values else 0.0,
        "descriptor_changed": shuffled_features["segment_counts"] != original_features["segment_counts"],
    }


__all__ = ["absolute_position_features", "deterministic_order_shuffle", "token_thirds"]
